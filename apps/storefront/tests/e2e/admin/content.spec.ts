import { test, expect } from './helpers';
import sharp from 'sharp';
test.use({role:'OWNER'});
test('an editor uploads a private image, previews a draft, then publishes it', async ({ page, browser }, info) => {
  await page.goto('/admin/media');
  const name = `ritual-${info.project.name}.png`;
  await page.locator('input[type=file]').setInputFiles({ name, mimeType:'image/png', buffer:await sharp({create:{width:10,height:10,channels:3,background:'#2f8751'}}).png().toBuffer() });
  await page.getByLabel('Image description').fill('A tiny test ritual image');
  await page.getByRole('button',{name:'Upload image',exact:true}).click();
  const card = page.locator('.a-card').filter({has:page.getByRole('heading',{name,exact:true})});
  await expect(card).toBeVisible();
  const path = await card.getByLabel(`Path for ${name}`).inputValue();
  const visitor = await browser.newContext({storageState:{cookies:[],origins:[]}});
  expect(await visitor.cookies()).toHaveLength(0);
  expect((await visitor.request.get(new URL(path,page.url()).href)).status()).toBe(404);
  const key = info.project.name === 'mobile-390' ? 'about' : info.project.name === 'tablet-768' ? 'ingredients-sourcing' : 'journal';
  await page.goto(`/admin/content/${key}`);
  const original = await page.getByLabel('Heading',{exact:true}).inputValue();
  const title = `A considered ritual ${info.project.name}`;
  await page.getByLabel('Heading',{exact:true}).fill(title);
  await page.getByLabel('Page image',{exact:true}).selectOption(path);
  await page.getByRole('button',{name:'Save draft',exact:true}).click();
  await expect(page.getByText(/Revision 1\./)).toBeVisible();
  const publicPage = await visitor.newPage(); await publicPage.goto(new URL(`/${key}`,page.url()).href);
  await expect(publicPage.getByRole('heading',{level:1})).not.toHaveText(title);
  const preview = await page.context().newPage();await preview.goto(new URL(`/${key}?preview=${key}`,page.url()).href);
  await expect(preview.getByRole('heading',{level:1})).toHaveText(title);await preview.close();
  await page.getByRole('button',{name:'Publish saved draft'}).click();
  await expect(page.getByText('Published. The storefront now uses this version.')).toBeVisible();
  await publicPage.reload();await expect(publicPage.getByRole('heading',{level:1})).toHaveText(title);
  expect((await visitor.request.get(new URL(path,page.url()).href)).status()).toBe(200);
  // Restore the original heading while keeping history; use the current revision token.
  await page.getByLabel('Heading',{exact:true}).fill(original);
  await page.getByRole('button',{name:'Save draft',exact:true}).click();
  await expect(page.getByText(/Revision 3\./)).toBeVisible();
  await page.getByRole('button',{name:'Publish saved draft'}).click();
  await expect(page.getByText(/Revision 4\./)).toBeVisible();
  await visitor.close();
});
